Q = Q[:30]

# 旋轉選項，讓正解平均落在 A/B/C/D（依題數自動平均分配）
n = len(Q)
TARGET = [i % 4 for i in range(n)]
KEEP = set()   # 選項有自然順序的題目不要轉
data = []
for i, (q, o, a, e) in enumerate(Q):
    assert len(o) == 4 and 0 <= a <= 3, q
    assert len(set(o)) == 4, q
    if i not in KEEP:
        k = (TARGET[i] - a) % 4
        o = o[-k:] + o[:-k] if k else o
        a = TARGET[i]
    data.append({"q": q, "o": o, "a": a, "e": e})

assert len(data) == len(Q), len(data)
assert len({d["q"] for d in data}) == len(Q)

